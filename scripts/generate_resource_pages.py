#!/usr/bin/env python3
"""Generate a detail page for every catalog resource, plus a comparison page.

    python scripts/generate_resource_pages.py            # write
    python scripts/generate_resource_pages.py --check    # fail if stale (CI)

Writes:
    public/r/<slug>.html      one page per resource (spec section 8.4)
    public/compare.html       side-by-side comparison (spec section 8.5)
    public/explore.html       browsable index of everything (spec section 8.3)

Design rule for these pages, from spec section 16.3: never show a bare
"verified" badge. Every claim on the page states what was checked, when, by
whom, and against what evidence — or says plainly that nothing was checked.
An unverified record must not look like a verified one.
"""

